import {readFileSync} from 'node:fs';

const configURL = new URL('./zigbee2mqtt-multicontrol.config.json', import.meta.url);

function invalid(path, requirement) {
    throw new Error(`MultiControl configuration: ${path} ${requirement}`);
}

function nonEmptyString(value, path) {
    if (typeof value !== 'string' || value.trim().length === 0) {
        invalid(path, 'must be a non-empty string');
    }
    return value;
}

function loadConfig() {
    let contents;
    try {
        contents = readFileSync(configURL, 'utf8');
    } catch (error) {
        throw new Error(`MultiControl: cannot read zigbee2mqtt-multicontrol.config.json beside the extension (${error.code ?? 'read error'})`);
    }

    let config;
    try {
        config = JSON.parse(contents);
    } catch {
        // Do not echo private configuration contents in a parse error.
        throw new Error('MultiControl: zigbee2mqtt-multicontrol.config.json contains malformed JSON');
    }

    if (!Array.isArray(config?.pairs) || config.pairs.length === 0) {
        invalid('pairs', 'must be a non-empty array');
    }

    const ieeeAddresses = new Set();
    const virtualIds = new Set();
    const deviceIds = new Set();
    const pairs = config.pairs.map((pair, index) => {
        const path = `pairs[${index}]`;
        if (!Array.isArray(pair?.devices) || pair.devices.length !== 2) {
            invalid(`${path}.devices`, 'must contain exactly 2 devices');
        }
        const devices = pair.devices.map((device, deviceIndex) => {
            const devicePath = `${path}.devices[${deviceIndex}]`;
            const ieee = nonEmptyString(device?.ieee, `${devicePath}.ieee`).toLowerCase();
            const name = nonEmptyString(device?.name, `${devicePath}.name`);
            if (ieeeAddresses.has(ieee)) {
                invalid(`${devicePath}.ieee`, 'must be unique across all devices and pairs');
            }
            ieeeAddresses.add(ieee);
            return {ieee, name};
        });
        const virtual = {};
        for (const field of ['id', 'name', 'deviceId', 'deviceName']) {
            virtual[field] = nonEmptyString(pair.virtual?.[field], `${path}.virtual.${field}`);
        }
        for (const [field, seen] of [['id', virtualIds], ['deviceId', deviceIds]]) {
            if (seen.has(virtual[field])) {
                invalid(`${path}.virtual.${field}`, 'must be unique across pairs');
            }
            seen.add(virtual[field]);
        }
        return {devices, virtual};
    });
    return {pairs};
}

export default class MultiControl {
    constructor(
        zigbee,
        mqtt,
        state,
        publishEntityState,
        eventBus,
        enableDisableExtension,
        restartCallback,
        addExtension,
        settings,
        logger,
    ) {
        this.mqtt = mqtt;
        this.eventBus = eventBus;
        this.settings = settings;
        this.logger = logger;

        const config = settings.get();

        this.baseTopic = config.mqtt.base_topic;

        this.discoveryTopic =
            config.homeassistant?.discovery_topic ??
            'homeassistant';

        this.pairs = loadConfig().pairs.map((pair) => ({
            ...pair,
            virtual: {
                ...pair.virtual,
                commandTopic: `${this.baseTopic}/virtual/${pair.virtual.id}/set`,
                stateTopic: `${this.baseTopic}/virtual/${pair.virtual.id}/state`,
                discoveryTopic: `${this.discoveryTopic}/switch/${pair.virtual.id}/config`,
            },
        }));

        this.devices = Object.create(null);
        this.pairsByCommandTopic = new Map();
        for (const pair of this.pairs) {
            this.pairsByCommandTopic.set(pair.virtual.commandTopic, pair);
            for (const [index, device] of pair.devices.entries()) {
                this.devices[device.ieee] = {
                    name: device.name,
                    peer: pair.devices[1 - index].ieee,
                    pair,
                };
            }
        }

        /*
         * Last known real state of each device.
         */
        this.currentState = new Map();

        /*
         * Commands generated by this extension.
         *
         * ieee -> {
         *     state: 'ON' | 'OFF',
         *     until: timestamp
         * }
         */
        this.expected = new Map();

        /*
         * Long enough to cover delayed device reports.
         */
        this.expectedTimeoutMs = 5000;

        /*
         * Duplicate-report protection.
         */
        this.lastHandled = new Map();
        this.debounceMs = 300;

        this.logger.info('Loaded MultiControl');
    }

    async start() {
        this.eventBus.onStateChange(
            this,
            this.onStateChange.bind(this),
        );

        this.eventBus.onMQTTMessage(
            this,
            this.onMQTTMessage.bind(this),
        );

        await this.publishHomeAssistantDiscovery();

        this.logger.info('MultiControl started');
    }

    stop() {
        this.eventBus.removeListeners(this);

        this.logger.info('MultiControl stopped');
    }

    /*
     * ============================================================
     * DEVICE STATE CHANGE
     * ============================================================
     */

    async onStateChange(data) {
        const {entity, update} = data;

        if (!entity || !update) {
            return;
        }

        const newState = update.state;

        if (newState !== 'ON' && newState !== 'OFF') {
            return;
        }

        const ieee = this.getIEEE(entity);

        if (!ieee) {
            return;
        }

        const device = this.devices[ieee];

        if (!device) {
            return;
        }

        const now = Date.now();
        const previousState =
            this.currentState.get(ieee);

        /*
         * Always remember the actually reported state first.
         */
        this.currentState.set(
            ieee,
            newState,
        );

        /*
         * --------------------------------------------------------
         * COMMAND ACK / REFLECTED REPORT
         * --------------------------------------------------------
         *
         * If this device was commanded by us, do not propagate
         * its return report to the peer.
         */
        const expected =
            this.expected.get(ieee);

        if (expected) {
            if (now <= expected.until) {
                if (newState === expected.state) {
                    this.expected.delete(ieee);

                    this.logger.debug(
                        `MultiControl: confirmed ` +
                        `${device.name} = ${newState}`,
                    );

                    await this.publishVirtualState(device.pair);

                    return;
                }

                /*
                 * Unexpected intermediate report while our command
                 * is still pending.
                 *
                 * Ignore it for propagation. This is deliberately
                 * conservative to prevent ON/OFF feedback storms.
                 */
                this.logger.debug(
                    `MultiControl: ignoring intermediate ` +
                    `${device.name} = ${newState}, ` +
                    `expected ${expected.state}`,
                );

                await this.publishVirtualState(device.pair);

                return;
            }

            /*
             * Pending command timed out.
             */
            this.expected.delete(ieee);
        }

        /*
         * --------------------------------------------------------
         * DUPLICATE REPORT
         * --------------------------------------------------------
         */

        if (previousState === newState) {
            await this.publishVirtualState(device.pair);
            return;
        }

        /*
         * Extra short-term debounce protection.
         */
        const lastHandled =
            this.lastHandled.get(ieee);

        if (
            lastHandled &&
            lastHandled.state === newState &&
            now - lastHandled.time < this.debounceMs
        ) {
            return;
        }

        this.lastHandled.set(
            ieee,
            {
                state: newState,
                time: now,
            },
        );

        this.logger.info(
            `MultiControl: ` +
            `${device.name} -> ${newState}`,
        );

        /*
         * --------------------------------------------------------
         * PROPAGATE TO PEER
         * --------------------------------------------------------
         */

        const peerIEEE =
            device.peer;

        const peer =
            this.devices[peerIEEE];

        if (!peer) {
            return;
        }

        const peerState =
            this.currentState.get(peerIEEE);

        /*
         * Peer is already correct.
         */
        if (peerState === newState) {
            this.logger.debug(
                `MultiControl: ` +
                `${peer.name} already ${newState}`,
            );

            await this.publishVirtualState(device.pair);

            return;
        }

        await this.commandDevice(
            peerIEEE,
            newState,
        );

        await this.publishVirtualState(device.pair);
    }

    /*
     * ============================================================
     * VIRTUAL HOME ASSISTANT SWITCH COMMAND
     * ============================================================
     */

    async onMQTTMessage(data) {
        const pair = data && this.pairsByCommandTopic.get(data.topic);
        if (!pair) {
            return;
        }

        const command =
            String(data.message)
                .trim()
                .toUpperCase();

        if (
            command !== 'ON' &&
            command !== 'OFF'
        ) {
            this.logger.warning(
                `MultiControl: invalid virtual command: ` +
                `${command}`,
            );

            return;
        }

        this.logger.info(
            `MultiControl: ` +
            `${pair.virtual.name} -> ${command}`,
        );

        /*
         * Command both devices individually.
         *
         * No Zigbee group command is used.
         */
        for (
            const {ieee}
            of pair.devices
        ) {
            const current =
                this.currentState.get(ieee);

            if (current === command) {
                continue;
            }

            await this.commandDevice(
                ieee,
                command,
            );
        }
    }

    /*
     * ============================================================
     * SEND INDIVIDUAL DEVICE COMMAND
     * ============================================================
     */

    async commandDevice(ieee, state) {
        const device =
            this.devices[ieee];

        if (!device) {
            return;
        }

        /*
         * Register expected state BEFORE injecting the MQTT
         * command, otherwise a very fast response could arrive
         * before the suppression is active.
         */
        this.expected.set(
            ieee,
            {
                state,
                until:
                    Date.now() +
                    this.expectedTimeoutMs,
            },
        );

        const topic =
            `${this.baseTopic}/${device.name}/set`;

        const payload =
            JSON.stringify({
                state,
            });

        this.logger.info(
            `MultiControl: ` +
            `${device.name} <= ${state}`,
        );

        /*
         * Feed it through Zigbee2MQTT's normal incoming MQTT
         * command path.
         *
         * Device converters handle the resulting ON/OFF command.
         */
        this.mqtt.onMessage(
            topic,
            Buffer.from(payload),
        );
    }

    /*
     * ============================================================
     * IEEE EXTRACTION
     * ============================================================
     */

    getIEEE(entity) {
        if (
            typeof entity.device?.ieeeAddr ===
            'string'
        ) {
            return entity.device.ieeeAddr
                .toLowerCase();
        }

        if (
            typeof entity.ieeeAddr ===
            'string'
        ) {
            return entity.ieeeAddr
                .toLowerCase();
        }

        if (
            typeof entity.ID === 'string' &&
            entity.ID.startsWith('0x')
        ) {
            return entity.ID
                .toLowerCase();
        }

        return undefined;
    }

    /*
     * ============================================================
     * VIRTUAL SWITCH STATE
     * ============================================================
     */

    async publishVirtualState(pair) {
        const states =
            pair.devices.map(
                ({ieee}) =>
                    this.currentState.get(ieee),
            );

        /*
         * Virtual switch semantics:
         *
         * ON  = both physical switches are ON
         * OFF = at least one is OFF
         *
         * Do not publish anything until both states are known.
         */
        if (
            states.some(
                (value) => value === undefined,
            )
        ) {
            return;
        }

        const virtualState =
            states.every(
                (value) => value === 'ON',
            )
                ? 'ON'
                : 'OFF';

        await this.mqtt.publish(
            pair.virtual.stateTopic.slice(this.baseTopic.length + 1),
            virtualState,
            {
                // Zigbee2MQTT prepends baseTopic to the relative topic.
                baseTopic: this.baseTopic,
                clientOptions: {
                    retain: true,
                },
            },
        );

        this.logger.debug(
            `MultiControl: ` +
            `${pair.virtual.name} state = ` +
            `${virtualState}`,
        );
    }

    /*
     * ============================================================
     * HOME ASSISTANT MQTT DISCOVERY
     * ============================================================
     */

    async publishHomeAssistantDiscovery() {
        for (const pair of this.pairs) {
            await this.publishPairDiscovery(pair);
        }
    }

    async publishPairDiscovery(pair) {
        const config = {
            name: pair.virtual.name,

            unique_id:
                pair.virtual.id,

            command_topic:
                pair.virtual.commandTopic,

            state_topic:
                pair.virtual.stateTopic,

            payload_on: 'ON',
            payload_off: 'OFF',

            optimistic: false,

            icon: 'mdi:light-switch',

            device: {
                identifiers: [
                    pair.virtual.deviceId,
                ],

                name:
                    pair.virtual.deviceName,

                manufacturer:
                    'Custom Zigbee2MQTT extension',

                model:
                    'Virtual MultiControl',
            },
        };

        await this.mqtt.publish(
            pair.virtual.discoveryTopic.slice(this.discoveryTopic.length + 1),
            JSON.stringify(config),
            {
                baseTopic:
                    this.discoveryTopic,

                clientOptions: {
                    retain: true,
                },
            },
        );

        this.logger.info(
            `MultiControl: ` +
            `Home Assistant discovery published`,
        );
    }
}